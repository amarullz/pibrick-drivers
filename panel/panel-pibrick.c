static int pibrick_bl_update_status(struct backlight_device *bl)
{
	struct mipi_dsi_device *dsi = bl_get_data(bl);
	struct pibrick_panel *ctx = mipi_dsi_get_drvdata(dsi);
	u16 brightness = backlight_get_brightness(bl);

	if (ctx->panel_type == PIBRICK_PANEL_548) {
		if (brightness < 8000)
			brightness = 8000;
	} else {
		if (brightness < 256)
			brightness = 256;

		brightness = DIV_ROUND_CLOSEST(
			brightness * 1023U, 65535U);
	}

	return mipi_dsi_dcs_set_display_brightness_large(dsi, brightness);
}

static const struct backlight_ops pibrick_bl_ops = {
	.update_status = pibrick_bl_update_status,
};

static struct backlight_device *
pibrick_create_backlight(struct mipi_dsi_device *dsi)
{
	struct pibrick_panel *ctx = mipi_dsi_get_drvdata(dsi);
	struct device *dev = &dsi->dev;
	struct backlight_properties props = {
		.type = BACKLIGHT_RAW,
	};

	props.brightness = 0xffff;
	props.max_brightness = 0xffff;
	return devm_backlight_device_register(dev, PIBRICK_BACKLIGHT_NAME,
					      dev, dsi, &pibrick_bl_ops, &props);
}


static int pibrick_probe(struct mipi_dsi_device *dsi)
{
	struct device *dev = &dsi->dev;
	struct pibrick_panel *ctx;
	int ret;

	ctx = devm_kzalloc(dev, sizeof(*ctx), GFP_KERNEL);
	if (!ctx)
		return -ENOMEM;

	// Detect Display Type from Touchscreen I2C
	ctx->panel_type = pibrick_get_panel_type(dev);


	if (ctx->panel_type < 0)
		return dev_err_probe(dev, ctx->panel_type,
				     "Failed to detect piBrick display\n");

	ret = devm_regulator_bulk_get_const(dev,
					    ARRAY_SIZE(pibrick_supplies),
					    pibrick_supplies,
					    &ctx->supplies);
	if (ret < 0)
		return ret;

	ctx->reset_gpio = devm_gpiod_get(dev, "reset", GPIOD_OUT_LOW);
	if (IS_ERR(ctx->reset_gpio))
		return dev_err_probe(dev, PTR_ERR(ctx->reset_gpio),
				     "Failed to get reset-gpios\n");

	drm_panel_init(&ctx->panel, dev, &pibrick_panel_funcs,
		       DRM_MODE_CONNECTOR_DSI);

	ctx->dsi = dsi;
	ctx->profile = PIBRICK_PROFILE_NATURAL;
	mipi_dsi_set_drvdata(dsi, ctx);

	dsi->lanes = 4;
	dsi->format = MIPI_DSI_FMT_RGB888;

	//-- BURST MODE FROM 5.48"
	// dsi->mode_flags = MIPI_DSI_MODE_VIDEO |
	// 			MIPI_DSI_MODE_VIDEO_BURST |
	// 			MIPI_DSI_MODE_VIDEO_SYNC_PULSE |
	// 			MIPI_DSI_MODE_LPM;
	
	dsi->mode_flags = MIPI_DSI_MODE_VIDEO |
				MIPI_DSI_MODE_NO_EOT_PACKET |
				MIPI_DSI_CLOCK_NON_CONTINUOUS| MIPI_DSI_MODE_LPM;

	ctx->panel.prepare_prev_first = true;

	ctx->panel.backlight = pibrick_create_backlight(dsi);
	if (IS_ERR(ctx->panel.backlight))
		return dev_err_probe(dev, PTR_ERR(ctx->panel.backlight),
				     "Failed to create backlight\n");

	drm_panel_add(&ctx->panel);

	ret = mipi_dsi_attach(dsi);
	if (ret < 0) {
		dev_err(dev, "Failed to attach to DSI host: %d\n", ret);
		drm_panel_remove(&ctx->panel);
		return ret;
	}


	if (ctx->panel_type == PIBRICK_PANEL_392) {
		ret = device_create_file(dev, &dev_attr_color_profile);
		if (ret)
			dev_err(dev, "Failed to create color_profile sysfs entry: %d\n",
				ret);
	}

	ret = device_create_file(dev, &dev_attr_pibrick_display_enable);
	if (ret)
		dev_err(dev, "Failed to create pibrick_display_enable sysfs entry: %d\n",
			ret);

	dev_info(dev, "Detected piBrick %s display\n",
		 ctx->panel_type == PIBRICK_PANEL_548 ? "5.48-inch" : "3.92-inch");
	
	ret = device_create_file(dev, &dev_attr_pibrick_panel_type);
	if (ret)
		dev_warn(dev, "Failed to create pibrick_panel_type sysfs attribute\n");

	return 0;
}

static void pibrick_remove(struct mipi_dsi_device *dsi)
{
	struct pibrick_panel *ctx = mipi_dsi_get_drvdata(dsi);

	device_remove_file(&dsi->dev, &dev_attr_pibrick_display_enable);

	if (ctx->panel_type == PIBRICK_PANEL_392)
		device_remove_file(&dsi->dev, &dev_attr_color_profile);

	mipi_dsi_detach(dsi);
	drm_panel_remove(&ctx->panel);
}

