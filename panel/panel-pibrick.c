static enum drm_panel_orientation pibrick_panel_get_orientation(
	struct drm_panel *panel)
{
	struct pibrick_panel *ctx = to_pibrick_panel(panel);

	if (ctx->panel_type == PIBRICK_PANEL_548)
		return DRM_MODE_PANEL_ORIENTATION_BOTTOM_UP;

	return DRM_MODE_PANEL_ORIENTATION_NORMAL;
}

static int pibrick_panel_get_modes(struct drm_panel *panel,
				   struct drm_connector *connector)
{
	struct pibrick_panel *ctx = to_pibrick_panel(panel);
	struct drm_display_mode *mode;

	if (ctx->panel_type == PIBRICK_PANEL_548) {

		mode = drm_mode_duplicate(connector->dev, &pibrick_mode_548_60);
		if (!mode)
			return -ENOMEM;

		drm_mode_set_name(mode);
		mode->type = DRM_MODE_TYPE_DRIVER | DRM_MODE_TYPE_PREFERRED;
		connector->display_info.width_mm = mode->width_mm;
		connector->display_info.height_mm = mode->height_mm;
		drm_mode_probed_add(connector, mode);

		return 1;
	}

	mode = drm_mode_duplicate(connector->dev, &pibrick_mode_392_90);
	if (!mode)
		return -ENOMEM;

	drm_mode_set_name(mode);
	mode->type = DRM_MODE_TYPE_DRIVER | DRM_MODE_TYPE_PREFERRED;
	connector->display_info.width_mm = mode->width_mm;
	connector->display_info.height_mm = mode->height_mm;
	drm_mode_probed_add(connector, mode);

	mode = drm_mode_duplicate(connector->dev, &pibrick_mode_392_60);
	if (!mode)
		return -ENOMEM;

	drm_mode_set_name(mode);
	mode->type = DRM_MODE_TYPE_DRIVER;
	drm_mode_probed_add(connector, mode);

	return 2;
}

