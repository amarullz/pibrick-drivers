static bool pibrick_i2c_device_present(struct i2c_adapter *adapter,
				       u16 addr)
{
	struct i2c_msg msg = {
		.addr = addr,
		.flags = I2C_M_RD,
		.len = 0,
		.buf = NULL,
	};

	return i2c_transfer(adapter, &msg, 1) == 1;
}

static int pibrick_get_panel_type(struct device *dev)
{
	struct i2c_adapter *adapter;
	struct gpio_desc *reset_gpio;
	bool has_ft5x06;
	bool has_hynitron;
	int ret;

	/*
	 * Touchscreen reset is active-low:
	 */
	reset_gpio = devm_gpiod_get_optional(dev, "touch-reset",
					     GPIOD_OUT_LOW);
	if (IS_ERR(reset_gpio))
		return dev_err_probe(dev, PTR_ERR(reset_gpio),
				     "Failed to get touchscreen reset GPIO\n");

	if (reset_gpio) {
		/* Activate Touchscreen for detection */
gpiod_set_value_cansleep(reset_gpio, 1);
                msleep(50);
		gpiod_set_value_cansleep(reset_gpio, 0);
		msleep(50);
	}

	int i;
	/* Detect up to 10 times */
	for (i=0;i<10;i++){
		adapter = i2c_get_adapter(0);
		if (!adapter) {
			dev_warn(dev,
				"Unable to access I2C bus 0, "
				"defaulting to 3.92-inch\n");
			return PIBRICK_PANEL_392;
		}

		has_ft5x06 = pibrick_i2c_device_present(adapter, 0x38);
		has_hynitron = pibrick_i2c_device_present(adapter, 0x5a);

		i2c_put_adapter(adapter);

		dev_info(dev,
			"Panel detection: FT5x06(0x38)=%s "
			"Hynitron(0x5a)=%s\n",
			has_ft5x06 ? "present" : "absent",
			has_hynitron ? "present" : "absent");

		if (has_ft5x06 && !has_hynitron)
			return PIBRICK_PANEL_548;

		if (has_hynitron && !has_ft5x06)
			return PIBRICK_PANEL_392;
		
		msleep(50);
	}

	if (!has_ft5x06 && !has_hynitron)
		dev_warn(dev,
			"No piBrick touchscreen detected, "
			"defaulting to 3.92-inch\n");
	else
		dev_warn(dev,
			"Both piBrick touchscreen addresses detected, "
			"defaulting to 3.92-inch\n");

	return PIBRICK_PANEL_392;
}

