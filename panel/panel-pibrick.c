static int pibrick_panel_prepare(struct drm_panel *panel)
{
	struct pibrick_panel *ctx = to_pibrick_panel(panel);
	int ret;

	ret = regulator_bulk_enable(ARRAY_SIZE(pibrick_supplies), ctx->supplies);
	if (ret < 0)
		return ret;

	pibrick_panel_reset(ctx);

	if (ctx->panel_type == PIBRICK_PANEL_548)
		ret = pibrick_panel_init_548(ctx);
	else
		ret = pibrick_panel_init_392(ctx);

	if (ret < 0) {
		gpiod_set_value_cansleep(ctx->reset_gpio, 1);
		regulator_bulk_disable(ARRAY_SIZE(pibrick_supplies), ctx->supplies);
		return ret;
	}

	return 0;
}

static int pibrick_panel_enable(struct drm_panel *panel)
{
	struct pibrick_panel *ctx = to_pibrick_panel(panel);
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	ctx->dsi->mode_flags |= MIPI_DSI_MODE_LPM;

	mipi_dsi_dcs_exit_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 50);
	mipi_dsi_dcs_set_display_on_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 20);

	ctx->enabled = true;
	return dsi_ctx.accum_err;
}

static int pibrick_panel_disable(struct drm_panel *panel)
{
	struct pibrick_panel *ctx = to_pibrick_panel(panel);
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	ctx->dsi->mode_flags |= MIPI_DSI_MODE_LPM;

	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 50);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 20);

	ctx->enabled = false;
	return dsi_ctx.accum_err;
}

static int pibrick_panel_unprepare(struct drm_panel *panel)
{
	struct pibrick_panel *ctx = to_pibrick_panel(panel);

	pibrick_panel_off(ctx);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);

	regulator_bulk_disable(ARRAY_SIZE(pibrick_supplies), ctx->supplies);

	return 0;
}

static void pibrick_panel_shutdown(struct mipi_dsi_device *dsi)
{
	struct pibrick_panel *ctx = mipi_dsi_get_drvdata(dsi);

	pibrick_panel_off(ctx);
	gpiod_set_value_cansleep(ctx->reset_gpio, 1);
}


