static int pibrick_apply_color_profile(struct pibrick_panel *ctx)
{
	switch (ctx->profile) {

	case PIBRICK_PROFILE_NATURAL:
		return pibrick_colorprofile_natural(ctx);

	case PIBRICK_PROFILE_VIVID:
		return pibrick_colorprofile_vivid(ctx);

	case PIBRICK_PROFILE_SRGB:
		return pibrick_colorprofile_srgb(ctx);

	case PIBRICK_PROFILE_WARM:
		return pibrick_colorprofile_warm(ctx);

	case PIBRICK_PROFILE_COLD:
		return pibrick_colorprofile_cold(ctx);

	case PIBRICK_PROFILE_NIGHT:
		return pibrick_colorprofile_night(ctx);

	case PIBRICK_PROFILE_SOFT:
		return pibrick_colorprofile_soft(ctx);
	default:
		return pibrick_colorprofile_natural(ctx);
	}

	return -EINVAL;
}
static ssize_t color_profile_show(
	struct device *dev,
	struct device_attribute *attr,
	char *buf)
{
	struct pibrick_panel *ctx = dev_get_drvdata(dev);
	const char *name = "unknown";
	switch (ctx->profile) {
		case PIBRICK_PROFILE_NATURAL: name = "natural"; break;
		case PIBRICK_PROFILE_VIVID:   name = "vivid"; break;
		case PIBRICK_PROFILE_SRGB:    name = "srgb"; break;
		case PIBRICK_PROFILE_WARM:    name = "warm"; break;
		case PIBRICK_PROFILE_COLD:    name = "cold"; break;
		case PIBRICK_PROFILE_NIGHT:   name = "night"; break;
		case PIBRICK_PROFILE_SOFT:    name = "soft"; break;
	}
	return sprintf(buf, "%s\n", name);
}
static ssize_t color_profile_store(
	struct device *dev,
	struct device_attribute *attr,
	const char *buf,
	size_t count)
{
	struct pibrick_panel *ctx = dev_get_drvdata(dev);

	if (ctx->panel_type != PIBRICK_PANEL_392)
		return -EOPNOTSUPP;

	if (sysfs_streq(buf, "natural"))
		ctx->profile = PIBRICK_PROFILE_NATURAL;

	else if (sysfs_streq(buf, "vivid"))
		ctx->profile = PIBRICK_PROFILE_VIVID;

	else if (sysfs_streq(buf, "srgb"))
		ctx->profile = PIBRICK_PROFILE_SRGB;

	else if (sysfs_streq(buf, "warm"))
		ctx->profile = PIBRICK_PROFILE_WARM;

	else if (sysfs_streq(buf, "cool"))
		ctx->profile = PIBRICK_PROFILE_COLD;

	else if (sysfs_streq(buf, "cold"))
		ctx->profile = PIBRICK_PROFILE_COLD;

	else if (sysfs_streq(buf, "night"))
		ctx->profile = PIBRICK_PROFILE_NIGHT;

	else if (sysfs_streq(buf, "soft"))
		ctx->profile = PIBRICK_PROFILE_SOFT;

	else
		return -EINVAL;

	return pibrick_apply_color_profile(ctx) ? -EIO : count;
}

